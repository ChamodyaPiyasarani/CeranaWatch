// BeeDetect.h - decides if a few seconds of sound are bee hive sound or something else.
// Made for CeranaNode (CeranaWatch). Runs on the ESP32, no internet needed.
// Model: base 10 Oct 2026 (70 hives)
//
// How it works: the sound is cut into 1024-sample frames (64 ms at 16 kHz). For each window of
// 46 frames (about 3 seconds) it measures 50 numbers about the shape of the sound (20 frequency bands,
// how much each band moves, how steady the loudness is, how "noisy" or "tonal" it is, where the energy
// sits) and a small neural network (50 -> 16 -> 1) turns them into a bee-sound probability.
// Trained in Python on 70 Apis cerana hives in Sri Lanka against 57 other sound types (ESC-50, MS-SNSD)
// and synthetic room sounds.
// Tested on apiaries and sound files it had not seen (10-second readings): with the device's rule
// "bees when 3 of the last 4 readings pass", bees were reported in about 90% of hive readings and
// other sounds in about 1% (household sounds about 4%). Phone-microphone recordings; the INMP441 in a
// house gave more false bee readings, which is why the device can be taught (see below).
//
// Teaching: the last layer (16 -> 1) can be fitted again on the device with windows heard in the
// beekeeper's own place ("no bees here" / "bees here"), together with 480 stored examples, so the
// device learns its own microphone and room. See fineTune().
//
