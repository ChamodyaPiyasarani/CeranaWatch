// ---------- the last layer, which teaching can change ----------
struct Head { float w[HIDDEN]; float b; };

inline Head baseHead() {
  Head h;
  for (int i = 0; i < HIDDEN; i++) h.w[i] = BD_W2[i];
  h.b = BD_B2;
  return h;
}

static Head head = baseHead();   // the layer in use now

inline float headProbability(const Head& hd, const float* hid) {
  float out = hd.b;
  for (int i = 0; i < HIDDEN; i++) out += hid[i] * hd.w[i];
  return 1.0f / (1.0f + expf(-out));
}

// The 16 hidden values for 50 measured numbers.
inline void hiddenFromFeatures(const float* feats, float* hid) {
  float x[FEATURES];
  for (int i = 0; i < FEATURES; i++) x[i] = (feats[i] - BD_MEAN[i]) / BD_SCALE[i];
  for (int h = 0; h < HIDDEN; h++) {
    float a = BD_B1[h];
    for (int i = 0; i < FEATURES; i++) a += x[i] * BD_W1[i * HIDDEN + h];
    hid[h] = a > 0 ? a : 0;
  }
}

// Fits the last layer again: the 480 stored examples plus the taught windows (label 1 = bees,
// 0 = no bees). Taught windows count 3 times. It starts from the trained layer and is pulled back
// towards it, so a few minutes of teaching cannot break the detector. Takes well under a second.
inline Head fineTune(const float* taught, const unsigned char* labels, int nTaught) {
  const int nStore = STORE_BEE + STORE_OTHER;
  const int n = nStore + nTaught;
  const double wTaught = 3.0;
  const double wMean = (nStore + wTaught * nTaught) / n;
  double w[HIDDEN];
  double b = BD_B2;
  for (int i = 0; i < HIDDEN; i++) w[i] = BD_W2[i];
  for (int step = 0; step < 400; step++) {
    double gw[HIDDEN];
    for (int i = 0; i < HIDDEN; i++) gw[i] = 0.0;
    double gb = 0.0;
    for (int e = 0; e < n; e++) {
      const float* h;
      double y, wt;
      if (e < STORE_BEE) { h = &BD_STORE_BEE[e * HIDDEN]; y = 1.0; wt = 1.0; }
      else if (e < nStore) { h = &BD_STORE_OTHER[(e - STORE_BEE) * HIDDEN]; y = 0.0; wt = 1.0; }
      else { h = &taught[(e - nStore) * HIDDEN]; y = labels[e - nStore] ? 1.0 : 0.0; wt = wTaught; }
      double z = b;
      for (int i = 0; i < HIDDEN; i++) z += (double)h[i] * w[i];
      double p = 1.0 / (1.0 + exp(-z));
      double g = (wt / wMean) * (p - y) / n;
      for (int i = 0; i < HIDDEN; i++) gw[i] += (double)h[i] * g;
      gb += g;
    }
    for (int i = 0; i < HIDDEN; i++) w[i] -= 0.5 * (gw[i] + 1.0 * (w[i] - BD_W2[i]) / n);
    b -= 0.5 * gb;
  }
  Head out;
  for (int i = 0; i < HIDDEN; i++) out.w[i] = (float)w[i];
  out.b = (float)b;
  return out;
}

// Collects one window of frames and gives the bee-sound probability.
class Window {
 public:
  void reset() {
    frames = 0;
    fluxSum = 0.0; fluxCount = 0;
    flatLoSum = 0.0; flatHiSum = 0.0;
    memset(specSum, 0, sizeof(specSum));
  }

  bool full() const { return frames >= WINDOW_FRAMES; }
  int count() const { return frames; }

  // power[k] = re[k]^2 + im[k]^2 for k = 0..512, from a Hann-windowed frame with its mean removed
  void addFrame(const float* power) {
    if (frames >= WINDOW_FRAMES) return;
    double total = 0.0;
    for (int k = 0; k < BINS; k++) total += power[k];
    // 20 band energies and the frame loudness
    double tot = 0.0;
    for (int b = 0; b < 20; b++) {
      double s = 0.0;
      for (int k = BAND_LO[b]; k <= BAND_HI[b]; k++) s += power[k];
      s += TINY;
      band[frames][b] = (float)s;
      tot += s;
    }
    totDb[frames] = (float)(10.0 * log10(tot));
    // flatness 100-1000 Hz (bins 7..63) and 1-4 kHz (bins 64..255)
    flatLoSum += flatness(power, 7, 63);
    flatHiSum += flatness(power, 64, 255);
    // spectral flux of the normalised spectrum
    double norm = total + TINY;
    if (frames > 0) {
      double f = 0.0;
      for (int k = 0; k < BINS; k++) {
        float p = (float)(power[k] / norm);
        f += fabsf(p - prevNorm[k]);
        prevNorm[k] = p;
      }
      fluxSum += f; fluxCount++;
    } else {
      for (int k = 0; k < BINS; k++) prevNorm[k] = (float)(power[k] / norm);
    }
    for (int k = 0; k < BINS; k++) specSum[k] += power[k];
    frames++;
  }

  // The 50 numbers (the same as dfeats2.feats in Python).
  void features(float* x) const {
    const int n = frames;
    double meanDb[20];
    double meanOfMeanDb = 0.0;
    for (int b = 0; b < 20; b++) {
      double s = 0.0;
      for (int f = 0; f < n; f++) s += band[f][b];
      meanDb[b] = 10.0 * log10(s / n);
      meanOfMeanDb += meanDb[b];
    }
    meanOfMeanDb /= 20.0;
    for (int b = 0; b < 20; b++) x[b] = (float)(meanDb[b] - meanOfMeanDb);
    for (int b = 0; b < 20; b++) {
      double s = 0.0, s2 = 0.0;
      for (int f = 0; f < n; f++) { double v = 10.0 * log10((double)band[f][b]); s += v; s2 += v * v; }
      double m = s / n;
      double var = s2 / n - m * m;
      x[20 + b] = (float)sqrt(var > 0 ? var : 0);
    }
    // loudness movement, dips, frame-to-frame change
    double s = 0.0, s2 = 0.0;
    for (int f = 0; f < n; f++) { s += totDb[f]; s2 += (double)totDb[f] * totDb[f]; }
    double m = s / n, var = s2 / n - m * m;
    x[40] = (float)sqrt(var > 0 ? var : 0);
    float sorted[WINDOW_FRAMES];
    memcpy(sorted, totDb, sizeof(float) * n);
    for (int i = 1; i < n; i++) { float v = sorted[i]; int j = i - 1; while (j >= 0 && sorted[j] > v) { sorted[j + 1] = sorted[j]; j--; } sorted[j + 1] = v; }
    double med = (n % 2 == 1) ? sorted[n / 2] : 0.5 * ((double)sorted[n / 2 - 1] + sorted[n / 2]);
    int dips = 0;
    for (int f = 0; f < n; f++) if (totDb[f] < med - 6.0) dips++;
    x[41] = (float)dips / n;
    double d = 0.0;
    for (int f = 1; f < n; f++) d += fabs((double)totDb[f] - totDb[f - 1]);
    x[42] = (float)(n > 1 ? d / (n - 1) : 0.0);
    x[43] = (float)(flatLoSum / n);
    x[44] = (float)(flatHiSum / n);
    x[45] = (float)(fluxCount > 0 ? fluxSum / fluxCount : 0.0);
    // where the energy sits in the average spectrum
    static double S[BINS];   // static: too big for the stack
    for (int k = 0; k < BINS; k++) S[k] = specSum[k] / n + TINY;
    double num = 0.0, den = 0.0;
    for (int k = 7; k <= 256; k++) { num += (k * 15.625) * S[k]; den += S[k]; }
    x[46] = (float)log10(num / den);
    double mx = 0.0, sm = 0.0;
    for (int k = 7; k <= 44; k++) { if (S[k] > mx) mx = S[k]; sm += S[k]; }
    x[47] = (float)(10.0 * log10(mx / (sm / 38.0)));
    double bee = 0.0;
    for (int k = 7; k <= 38; k++) bee += S[k];
    x[48] = (float)(10.0 * log10(bee / den));
    double seg[57];
    for (int i = 0; i < 57; i++) seg[i] = 10.0 * log10(S[7 + i]);
    double r = 0.0, r2 = 0.0;
    for (int i = 2; i <= 54; i++) {
      double smooth = (seg[i - 2] + seg[i - 1] + seg[i] + seg[i + 1] + seg[i + 2]) / 5.0;
      double v = seg[i] - smooth; r += v; r2 += v * v;
    }
    double rm = r / 53.0, rv = r2 / 53.0 - rm * rm;
    x[49] = (float)sqrt(rv > 0 ? rv : 0);
  }

  // The 16 hidden values of this window.
  void hidden(float* hid) const {
    float x[FEATURES];
    features(x);
    hiddenFromFeatures(x, hid);
  }

  // Bee-sound probability (0..1) of this window, with the layer in use now.
  float probability() const {
    float hid[HIDDEN];
    hidden(hid);
    return headProbability(head, hid);
  }

 private:
  static double flatness(const float* power, int k1, int k2) {
    double logSum = 0.0, sum = 0.0;
    int count = k2 - k1 + 1;
    for (int k = k1; k <= k2; k++) { double p = (double)power[k] + TINY; logSum += log(p); sum += p; }
    return exp(logSum / count) / (sum / count);
  }

  int frames = 0;
  float band[WINDOW_FRAMES][20];
  float totDb[WINDOW_FRAMES];
  float prevNorm[BINS];
  double specSum[BINS];
  double fluxSum = 0.0; int fluxCount = 0;
  double flatLoSum = 0.0, flatHiSum = 0.0;
};

